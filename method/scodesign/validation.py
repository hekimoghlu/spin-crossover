"""Compare this reimplementation's outputs with the numbers reported in the manuscript.

The manuscript is read ONLY here, ONLY to print the comparison table; nothing read from it
feeds back into any computed quantity.

Verdicts
  match     |ours - paper| within half a unit of the paper's last displayed digit (or <=0.5% rel.)
  close     within 25 % relative, or 5 absolute units unless both values are below 1.5 in magnitude
  MISMATCH  otherwise
"""
import json
import os
import re

DEFAULT_PAPER = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..",
                             "papers", "paperA.tex")

NOT_REIMPLEMENTED_PREFIXES = {
    "nb": "materials-companion numbers (not methods of this paper)",
    "ml": "materials-companion numbers (not methods of this paper)",
    "mg": "materials-companion numbers (not methods of this paper)",
    "rs": "reference-state arm macros (compared via table tab_rsem / caldec instead)",
    "qasmCost": "QASM hardware cost estimate",
}


def parse_macros(tex):
    out = {}
    for m in re.finditer(r"\\newcommand\{\\(\w+)\}\{(.*)\}\s*$", tex, flags=re.M):
        out[m.group(1)] = m.group(2)
    return out


def to_number(s):
    t = s.replace(",", "").replace("$", "").strip()
    try:
        return float(t)
    except ValueError:
        return None


def decimals(s):
    t = s.replace(",", "").strip()
    return len(t.split(".")[1]) if "." in t else 0


def verdict(ours, paper_s):
    p = to_number(paper_s)
    if p is None or ours is None:
        return "text"
    half = 0.5 * 10 ** (-decimals(paper_s))
    d = abs(ours - p)
    if d <= half + 1e-9 or (p != 0 and d / abs(p) <= 0.005):
        return "match"
    small = max(abs(p), abs(ours)) < 1.5      # fractions, probabilities, correlations: relative test only
    if (d <= 5 and not small) or (p != 0 and d / abs(p) <= 0.25):
        return "close"
    return "MISMATCH"


def fmt(v):
    if isinstance(v, str):
        return v
    if v is None:
        return "-"
    if isinstance(v, (int, bool)) or (isinstance(v, float) and v.is_integer() and abs(v) < 1e7):
        return f"{int(v):,}"
    if abs(v) >= 1000:
        return f"{v:,.0f}"
    if abs(v) >= 10:
        return f"{v:.1f}"
    return f"{v:.3g}"


def parse_table(tex, name):
    m = re.search(r"%% begin %s\n(.*?)%% end %s" % (name, name), tex, flags=re.S)
    if not m:
        return []
    rows = []
    for line in m.group(1).splitlines():
        line = line.strip()
        if not line or line.startswith("\\bottomrule") or line.startswith("\\midrule"):
            continue
        cells = [c.strip() for c in line.rstrip("\\").split("&")]
        rows.append(cells)
    return rows


def write(results_path, out_md, paper_path=""):
    paper_path = paper_path or DEFAULT_PAPER
    with open(results_path) as f:
        R = json.load(f)
    with open(paper_path) as f:
        tex = f.read()
    paper = parse_macros(tex)
    body = tex[tex.find("\\begin{document}"):]
    M = dict(R["macros"])
    ver = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(results_path))), "qasm", "verification.json")
    if os.path.exists(ver):
        with open(ver) as f:
            M["qasmFiles"] = json.load(f)["n_native_files"]   # native ansatz + twin, three bases
    rows = []
    counts = {"match": 0, "close": 0, "MISMATCH": 0, "text": 0}
    missing = []
    skipped = {}
    for name, val in paper.items():
        if name in ("Hhb", "Tm", "dH", "dS", "cm", "LS", "HS"):
            continue
        if name in M:
            ours = M[name]
            v = verdict(ours if not isinstance(ours, str) else None, val)
            if isinstance(ours, str) and ours.replace(" ", "") == val.replace("$", "").replace(" ", ""):
                v = "match"
            counts[v] += 1
            rows.append((name, val, fmt(ours), v))
        else:
            pref = next((p for p in NOT_REIMPLEMENTED_PREFIXES if name.startswith(p)), None)
            if pref:
                skipped.setdefault(NOT_REIMPLEMENTED_PREFIXES[pref], []).append(name)
            elif "\\" + name in body:
                missing.append((name, val))
            else:
                missing.append((name, val))
    L = []
    L.append("# VALIDATION: manuscript numbers vs this independent reimplementation\n")
    L.append("This table is generated by `python3 -m scodesign validate` from `results/results.json`. "
             "The manuscript is parsed only to print the *paper value* column; no paper number is used as an "
             "input or output of the pipeline. Noise-derived quantities come from different random draws "
             "(and partly different unstated choices, see ASSUMPTIONS.md), so exact agreement is not expected "
             "for them; deterministic quantities (enumeration, ligand field, exact diagonalisation, prices, gate "
             "counts) are expected to match.\n")
    L.append("Verdicts: **match** = within the paper's displayed precision (or 0.5 % rel.); **close** = within 25 % "
             "relative, or 5 absolute units (the absolute rule is not applied when both values are below 1.5 in "
             "magnitude, i.e. to fractions, probabilities and correlations); **MISMATCH** = otherwise; text = non-numeric macro shown side by side.\n")
    L.append(f"Summary over {sum(counts.values())} compared macros: {counts['match']} match, {counts['close']} close, "
             f"{counts['MISMATCH']} MISMATCH, {counts['text']} text.\n")
    L.append(f"Run configuration: {json.dumps(R['config'])}; pipeline wall time {R['timing']['total']:.1f} s.\n")
    L.append("## 0. Why noise-derived numbers differ\n")
    L.append("- Every device number depends on random drift and shot draws; this code uses its own seeds, so single-draw "
             "quantities (the deployed fit `rmsPTc`, `corrA/B`, `maxPTc`, per-arm calibration rows `surr*`) scatter "
             "by tens of per cent between draws even with identical method.")
    L.append("- The dispatched set is a function of that one fit (band, threshold distances), so it differs in size and "
             "membership (here vs the paper's 53); all `u*`, `cl*`, `routed*`, cost-of-dispatched-set numbers "
             "inherit that difference (e.g. how many successful designs sit in the dispatched set fixes the "
             "raw-arm 'wrong' counts).")
    L.append("- Unstated details chosen here (ASSUMPTIONS.md): noiseless basis-change gates and state preparation, "
             "independent raw/mitigated histograms, folding-gate selection seed, readout correction with the "
             "exact published flip rate, drift only on the two-qubit error. These plausibly explain part of the "
             "differences in residual mitigation bias on the SWAP-routed platforms (ours smaller by ~5-12 K) and "
             "in the raw Cepheus calibration-compound bias (ours ~25 % larger); this was not isolated further.")
    L.append("- Implemented stack (sec. 6.3-6.7): the decoder, surrogate, proposer, escalation policy and QAOA "
             "objective have unstated architectures, hyper-parameters, penalty grids and objective constants; "
             "the choices made here are listed in ASSUMPTIONS.md 28-33. QAOA in particular depends entirely on "
             "the unstated value/cost/budget/penalty definition, so P(optimal) and the approximation ratio are "
             "not comparable in absolute terms. The surrogate study uses one independent noise draw (epoch 1); "
             f"its line fit gives {M.get('rdSurrDeviceLin', float('nan')):.0f} K held-out, a single-draw quantity.")
    L.append("- No parameter was tuned to approach the paper's values.\n")
    L.append("## 1. Macro-by-macro comparison\n")
    L.append("| macro | paper value | this reimplementation | verdict |")
    L.append("|---|---|---|---|")
    for r in rows:
        L.append(f"| `{r[0]}` | {r[1]} | {r[2]} | {r[3]} |")
    # ---- tables without macros
    L.append("\n## 2. Tables without per-cell macros\n")
    L.append("### Table tab_rsem (four arms, RMS K over calibration + dispatched complexes, six epochs)\n")
    L.append("| platform | shots | paper raw/ext/rsc/pmit | ours raw/ext/rsc/pmit |")
    L.append("|---|---|---|---|")
    prs = parse_table(tex, "tab_rsem")
    last = None
    for cells in prs:
        if len(cells) < 6:
            continue
        plat = cells[0] or last
        last = plat
        shots = int(cells[1].replace(",", ""))
        pv = [re.sub(r"\\textbf\{(.*?)\}", r"\1", c) for c in cells[2:6]]
        key = [k for k, v in {"Cepheus": "Rigetti", "Heron": "IBM", "Willow": "Google", "Helios": "Quantinuum",
                              "Forte": "IonQ"}.items() if v in plat][0]
        ours = [r for r in R["tab_rsem"] if r["platform"] == key and r["shots"] == shots][0]
        L.append(f"| {plat} | {shots:,} | {' / '.join(pv)} | "
                 f"{ours['raw']:.0f} / {ours['mit']:.0f} / {ours['rsc']:.0f} / {ours['pmit']:.0f} |")
    L.append("\n### Table tab_caldec (surrogate-only wrong decisions on the dispatched pairs: mean (worst) over six draws)\n")
    L.append("| platform | shots | paper ext / rsc / pmit | ours ext / rsc / pmit |")
    L.append("|---|---|---|---|")
    last = None
    for cells in parse_table(tex, "tab_caldec"):
        if len(cells) < 8:
            continue
        plat = cells[0] or last
        last = plat
        shots = int(cells[1].replace(",", ""))
        key = [k for k, v in {"Cepheus": "Rigetti", "Heron": "IBM", "Willow": "Google", "Helios": "Quantinuum",
                              "Forte": "IonQ"}.items() if v in plat][0]
        ours = [r for r in R["tab_caldec"] if r["platform"] == key and r["shots"] == shots][0]
        o = " / ".join(f"{ours[a]['mean']:.1f} ({ours[a]['max']})" for a in ("mit", "rsc", "pmit"))
        L.append(f"| {plat} | {shots:,} | {cells[2]} / {cells[4]} / {cells[6]} | {o} |")
    L.append("\n### Table tab_rough (device error D and crossing sigma*, K)\n")
    L.append("| platform | shots | paper D/sigma* ext, rsc, pmit | ours D/sigma* ext, rsc, pmit |")
    L.append("|---|---|---|---|")
    last = None
    for cells in parse_table(tex, "tab_rough"):
        if len(cells) < 8:
            continue
        plat = cells[0] or last
        last = plat
        shots = int(cells[1].replace(",", ""))
        key = [k for k, v in {"Cepheus": "Rigetti", "Heron": "IBM", "Willow": "Google", "Helios": "Quantinuum",
                              "Forte": "IonQ"}.items() if v in plat][0]
        pv = [c.replace("$", "") for c in cells[2:8]]
        oc = {c["arm"]: c for c in R["roughness"]["combos"] if c["platform"] == key and c["shots"] == shots}
        o = ", ".join(f"{oc[a]['D']:.0f}/{oc[a]['sigma_star']:.0f}" for a in ("mit", "rsc", "pmit"))
        L.append(f"| {plat} | {shots:,} | {pv[0]}/{pv[1]}, {pv[2]}/{pv[3]}, {pv[4]}/{pv[5]} | {o} |")
    L.append("\n### Table tab_scaling (analytic projection)\n")
    L.append("| space | paper (qubits, Givens, 2Q, fidelities C/H/W/He/F, r*) | ours |")
    L.append("|---|---|---|")
    for cells, ours in zip(parse_table(tex, "tab_scaling"), R["tab_scaling"]):
        f = ours["fidelity"]
        o = (f"{ours['qubits']}, {ours['givens']}, {ours['n2q']}, "
             + "/".join(f"{f[p]:.2f}" for p in ("Cepheus", "Heron", "Willow", "Helios", "Forte"))
             + f", {ours['r_star'] * 1e3:.2f}e-3")
        L.append(f"| {cells[0]} | {', '.join(c.replace('$', '') for c in cells[1:])} | {o} |")
    L.append("\n## 3. Paper quantities not reimplemented\n")
    for why, names in skipped.items():
        L.append(f"- {why}: {len(names)} macros (" + ", ".join(f"`{n}`" for n in names[:8])
                 + (", ..." if len(names) > 8 else "") + ")")
    if missing:
        L.append("\nOther paper macros with no counterpart computed here:\n")
        L.append(", ".join(f"`{n}`" for n, _ in missing))
    L.append("\n## 4. Internal checks of this reimplementation\n")
    fc = R["fullspace_check"]
    L.append(f"- Full ten-mode space vs ten-dimensional block on 12 random complexes: max |dE| singlet "
             f"{fc['max_dev_singlet']:.1e} cm^-1, quintet {fc['max_dev_quintet']:.1e} cm^-1 "
             f"(same with the standard spin-flip sign: {fc['max_dev_singlet_standard_sign']:.1e}).")
    L.append(f"- Pauli terms: {R['pauli']['n_terms']} in groups {R['pauli']['groups']} (Z group = 5 Z + 10 ZZ).")
    L.append(f"- Highest resting-complex T1/2: {R['max_resting_T']:.1f} K (paper: below 100 K).")
    L.append(f"- Calibration-point scatter about exact correlation energies: {R['cal_scatter_cm']:.0f} cm^-1 RMS "
             "(paper: about 800 cm^-1).")
    L.append(f"- Router tolerance range on dispatched candidates: {R['route_tolerances']['min']:.1f} to "
             f"{R['route_tolerances']['max']:.1f} K.")
    with open(out_md, "w") as f:
        f.write("\n".join(L) + "\n")
    print(f"[validate] {counts} -> {out_md}")
    return counts
